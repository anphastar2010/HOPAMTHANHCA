async function performLibraryUpdate() {
  const confirmBtn = q("confirmUpdateBtn");
  const summaryBox = q("modalSummaryBox");
  confirmBtn.disabled = true;
  confirmBtn.textContent = "Đang ghi songs.js...";

  // 1. Cancel pending autosave to coordinate safely with update
  clearTimeout(autoSaveTimer);

  // 2. Cache current active form before computing remaining state
  cacheCurrentForm();

  // 3. Compute remaining unapplied forms and preserve further typing
  const appliedIds = new Set(changes.map(c => String(c.op === "delete" ? (c.songId || c.song?.id) : c.song?.id)));
  const remainingSongForms = {};
  const editableFields = ["title", "artist", "key", "audio", "sheet", "content", "sourceUrl"];

  for (const [key, formVal] of Object.entries(songForms)) {
    if (!formVal || typeof formVal !== "object") continue;

    if (!appliedIds.has(key)) {
      // Unapplied song forms (e.g. "new" or other song in progress) -> preserve!
      remainingSongForms[key] = formVal;
    } else {
      // Song was queued in changes. Find the last approved change for this song
      const songChanges = changes.filter(c => String(c.op === "delete" ? (c.songId || c.song?.id) : c.song?.id) === key);
      const lastApprovedChange = songChanges[songChanges.length - 1];

      if (lastApprovedChange) {
        if (lastApprovedChange.op === "delete") {
          // Song was deleted in changeset, but form has content -> preserve!
          remainingSongForms[key] = formVal;
        } else {
          const approvedSong = lastApprovedChange.song || {};
          // Compare across all editable fields against final approved state
          const isFurtherModified = editableFields.some(field => {
            const formField = formVal[field] != null ? String(formVal[field]).trim() : "";
            const approvedField = approvedSong[field] != null ? String(approvedSong[field]).trim() : "";
            return formField !== approvedField;
          });

          if (isFurtherModified) {
            remainingSongForms[key] = formVal;
          }
        }
      }
    }
  }

  // 4. Construct remaining draft payload to persist atomically on server
  const currentSongData = (id != null || q("title")?.value.trim()) ? {
    id: id || Date.now(),
    title: q("title")?.value.trim() || "",
    artist: q("artist")?.value.trim() || "",
    key: q("key")?.value.trim() || "C",
    audio: q("audio")?.value.trim() || "",
    sheet: q("sheet")?.value.trim() || "",
    content: q("content")?.value || "",
    sourceUrl: q("sourceUrl")?.value.trim() || ""
  } : null;

  const remainingDraft = {
    activeSongId: id,
    song: currentSongData,
    songForms: remainingSongForms,
    changes: []
  };

  try {
    const res = await fetch("/api/update-library", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        changes,
        baseLibraryHash,
        expectedRevision: globalThis.HOPAM_DATA_REVISION,
        expectedLibraryHash: pendingReviewLibraryHash,
        reviewToken: pendingReviewToken,
        expectedDraftRevision: currentDraftRevision,
        remainingDraft,
        author: q("editorName")?.value || "Studio",
        _simulateDraftWriteError: Boolean(window.__simulateDraftWriteError)
      })
    });
    const result = await res.json();
    if (!result.ok && !result.libraryUpdated) {
      if (res.status === 409) {
        alert(`⚠️ XUNG ĐỘT: ${result.error}\nVui lòng kiểm tra lại.`);
      }
      throw new Error(result.error);
    }

    if (result.libraryUpdated) {
      // Success! Update local draft revision and hashes from server
      changes = [];
      songForms = remainingSongForms;
      pendingReviewToken = null;
      if (result.newLibraryHash) {
        baseLibraryHash = result.newLibraryHash;
      }
      if (result.draftConflict) {
        // Xung đột phiên bản nháp với tab khác!
        isDraftConflict = true;
        clearTimeout(autoSaveTimer);
        // KHÔNG cấp revision mới đó cho client cũ và KHÔNG tự lấy revision mới nhất rồi ghi đè!
        closeUpdateModal();
        updatePendingUi();
        if (q("draftStatusBadge")) {
          q("draftStatusBadge").className = "badge badge-danger";
          q("draftStatusBadge").textContent = "⚠️ Xung đột nháp (đã dừng autosave)";
        }
        showDraftConflictBanner(result.draftWarning);
        alert(
          `⚠️ XUNG ĐỘT BẢN NHÁP:\n- Thư viện songs.js đã được cập nhật thành công (${result.newCount} bài)!\n- Bản sao lưu: ${result.backupFile}\n- ${result.draftWarning}\n\nChế độ tự động lưu nháp đã TẠM DỪNG để bảo vệ bản nháp của phiên khác. Nội dung bạn đang gõ dở vẫn được giữ nguyên vẹn trên màn hình. Bạn có thể xuất bản nháp riêng hoặc tải lại nháp từ máy chủ.`
        );
      } else if (result.draftSaved === false) {
        // Lỗi I/O (không phải do xung đột phiên làm việc): gán actualDraftRevision để retry
        if (typeof result.actualDraftRevision === "number") {
          currentDraftRevision = result.actualDraftRevision;
        } else if (typeof result.newDraftRevision === "number") {
          currentDraftRevision = result.newDraftRevision;
        }
        closeUpdateModal();
        updatePendingUi();
        if (q("draftStatusBadge")) {
          q("draftStatusBadge").className = "badge badge-warn";
          q("draftStatusBadge").textContent = "Lưu nháp dở dang ⚠️";
        }
        alert(
          `⚠️ CẬP NHẬT THÀNH CÔNG MỘT PHẦN:\n- Thư viện songs.js đã được cập nhật thành công (${result.newCount} bài)!\n- Bản sao lưu: ${result.backupFile}\n- Nhưng lưu bản nháp thất bại: ${result.draftError || result.draftWarning}\n\nNội dung đang gõ dở vẫn được giữ an toàn trên màn hình. Hệ thống sẽ thử lưu lại bản nháp ngay.`
        );
        scheduleAutoSave();
      } else {
        // Cập nhật thư viện và lưu nháp thành công bình thường
        if (typeof result.newDraftRevision === "number") {
          currentDraftRevision = result.newDraftRevision;
        }
        closeUpdateModal();
        updatePendingUi();
        if (result.draftWarning) {
          alert(`✅ Cập nhật thư viện thành công!\n⚠️ Lưu ý bản nháp: ${result.draftWarning}`);
        } else {
          alert(`✅ Cập nhật thư viện thành công!\n- Tổng số bài: ${result.newCount}\n- Bản sao lưu: ${result.backupFile}`);
        }
      }

      // Re-fetch updated library in-place to preserve form inputs currently being typed
      try {
        const reloadRes = await fetch("/api/songs");
        if (reloadRes.ok) {
          const reloadData = await reloadRes.json();
          lib = reloadData.songs;
          drawList();
          checkValidation();
        }
      } catch (reloadErr) {
        // Do NOT window.location.reload() to protect unsaved forms
        console.warn("Không thể tự động tải lại danh sách bài hát tại chỗ:", reloadErr);
      }
      return;
    }
  } catch (error) {
    summaryBox.className = "validation-box err";
    summaryBox.textContent = "Không thể cập nhật: " + error.message;
    confirmBtn.disabled = false;
    confirmBtn.textContent = "Thử lại";
  }
}

