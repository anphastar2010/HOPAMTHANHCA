// Global Studio state
let lib = structuredClone(typeof songs === "undefined" ? [] : songs);
let id = null;
let history = [];
let changes = [];
let songForms = {}; // Cache uncommitted form values per song ID (or "new")
let previewTransposeSteps = 0;
let autoSaveTimer = null;
let isServerOnline = false;
let currentDraftRevision = 0;
let isDraftConflict = false;
let isRestoringDraft = false;
let baseLibraryHash = null; // Baseline hash when user started editing or loaded draft
let pendingReviewToken = null; // Token generated by /api/diff binding reviewed changes
let pendingReviewLibraryHash = null; // Hash of library at the moment of review
let currentDraftData = null;

const q = x => document.getElementById(x);
const fields = ["title", "artist", "key", "audio", "sheet", "content"];

const download = (name, text) => {
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([text], { type: "application/json" }));
  a.download = name;
  a.click();
};

function renderSongChords(container, text) {
  const fragment = document.createDocumentFragment();
  const parts = text.split(/(\[[^\]]+\])/g);
  parts.forEach(part => {
    if (/^\[[^\]]+\]$/.test(part)) {
      const chord = document.createElement("span");
      chord.className = "chord";
      chord.textContent = part.slice(1, -1);
      fragment.append(chord);
    } else {
      fragment.append(document.createTextNode(part));
    }
  });
  container.replaceChildren(fragment);
}

function updatePreview() {
  const title = q("title")?.value.trim() || "";
  const artist = q("artist")?.value.trim() || "";
  const key = q("key")?.value.trim() || "C";
  const rawContent = q("content")?.value || "";

  // Update preview title and artist
  if (q("previewTitle")) q("previewTitle").textContent = title || "(Chưa có tên bài)";
  if (q("previewArtist")) q("previewArtist").textContent = "Tác giả: " + (artist || "Chưa rõ");

  // Transpose preview
  const transposedKey = transposeKey(key, previewTransposeSteps);
  if (q("previewKeyDisplay")) q("previewKeyDisplay").textContent = transposedKey;

  const transposedContent = transposeText(rawContent, previewTransposeSteps, transposedKey);
  if (q("displayContent")) {
    renderSongChords(q("displayContent"), transposedContent);
  }

  // Keep hidden #preview updated for backward compatibility with smoke tests
  if (q("preview")) {
    q("preview").textContent = rawContent;
  }
}

function checkValidation() {
  const title = q("title").value.trim();
  const content = q("content").value;
  const key = q("key").value.trim();
  const validEl = q("valid");

  updatePreview();

  const openCount = (content.match(/\[/g) || []).length;
  const closeCount = (content.match(/\]/g) || []).length;

  if (!title && !content.trim()) {
    validEl.className = "validation-box err";
    validEl.textContent = "Cần tên bài và nội dung.";
    return false;
  }

  if (!title) {
    validEl.className = "validation-box err";
    validEl.textContent = "Vui lòng nhập tên bài hát.";
    return false;
  }

  if (!content.trim()) {
    validEl.className = "validation-box err";
    validEl.textContent = "Vui lòng nhập lời và hợp âm bài hát.";
    return false;
  }

  // Duplicate title check
  const duplicate = lib.find(s => s.id !== id && s.title.toLowerCase() === title.toLowerCase());
  if (duplicate) {
    validEl.className = "validation-box warn";
    validEl.textContent = `Cảnh báo: Tên bài trùng với bài có sẵn (ID ${duplicate.id}).`;
    return true;
  }

  // Unbalanced brackets check
  if (openCount !== closeCount) {
    validEl.className = "validation-box warn";
    validEl.textContent = `Cảnh báo: Ngoặc hợp âm chưa cân bằng (${openCount} '[' và ${closeCount} ']').`;
    return true;
  }

  validEl.className = "validation-box ok";
  validEl.textContent = "Sẵn sàng lưu.";
  return true;
}

function updatePendingUi() {
  const btn = q("updateLibraryBtn");
  const countEl = q("pendingChangesCount");
  const draftBadge = q("draftStatusBadge");

  if (changes.length > 0) {
    if (btn) btn.style.display = "block";
    if (countEl) countEl.textContent = String(changes.length);
    if (draftBadge) {
      draftBadge.className = "badge badge-warn";
      draftBadge.textContent = `Chưa cập nhật thư viện (${changes.length} thay đổi)`;
    }
  } else {
    if (btn) btn.style.display = "none";
    if (draftBadge) {
      draftBadge.className = "badge badge-neutral";
      draftBadge.textContent = "Thư viện đồng bộ";
    }
  }
}

function drawList() {
  const query = q("search").value.toLowerCase().trim();
  const listEl = q("list");
  listEl.replaceChildren();

  const filtered = lib.filter(s =>
    (s.title + " " + (s.artist || "") + " " + (s.content || "")).toLowerCase().includes(query)
  );

  filtered.sort((a, b) => a.title.localeCompare(b.title, "vi"));

  if (q("songCountDisplay")) {
    q("songCountDisplay").textContent = `${lib.length} bài`;
  }

  filtered.forEach(s => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "song" + (s.id === id ? " active" : "");

    const textSpan = document.createElement("span");
    textSpan.textContent = `${s.title} · ${s.artist || "Chưa rõ"}`;
    btn.append(textSpan);

    // If this song has pending change in changes array, mark it
    if (changes.some(c => c.song?.id === s.id || c.songId === s.id)) {
      const badge = document.createElement("span");
      badge.className = "song-draft-badge";
      badge.textContent = "Đã sửa";
      btn.append(badge);
    }

    btn.onclick = () => loadSong(s);
    listEl.append(btn);
  });
}

function cacheCurrentForm() {
  if (isRestoringDraft) return;
  const currentKey = id != null ? String(id) : "new";
  songForms[currentKey] = {
    title: q("title")?.value || "",
    artist: q("artist")?.value || "",
    key: q("key")?.value || "C",
    audio: q("audio")?.value || "",
    sheet: q("sheet")?.value || "",
    content: q("content")?.value || "",
    sourceUrl: q("sourceUrl")?.value || ""
  };
}

function loadSong(s, useCache = true) {
  if (id !== s.id) {
    cacheCurrentForm();
  }
  id = s.id;
  const key = String(s.id);
  const cached = useCache ? songForms[key] : null;

  fields.forEach(k => {
    if (q(k)) q(k).value = (cached && cached[k] !== undefined) ? cached[k] : (s[k] || "");
  });
  if (q("sourceUrl")) q("sourceUrl").value = (cached && cached.sourceUrl !== undefined) ? cached.sourceUrl : (s.sourceUrl || "");
  if (q("heading")) q("heading").textContent = "Chỉnh sửa: " + (q("title")?.value || s.title);
  previewTransposeSteps = 0;
  pendingReviewToken = null; // Invalidate previous review token on form change
  drawList();
  checkValidation();
  scheduleAutoSave();
}

function isFormDirty() {
  const currentTitle = q("title")?.value.trim() || "";
  const currentContent = q("content")?.value.trim() || "";
  if (!id) return Boolean(currentTitle || currentContent);
  const original = lib.find(s => s.id === id);
  if (!original) return true;
  return (original.title || "").trim() !== currentTitle || (original.content || "").trim() !== currentContent;
}

function blankSong(force = false) {
  const isEmbeddedSmoke = window.parent !== window;
  if (!force && !isEmbeddedSmoke && isFormDirty()) {
    if (!confirm("Bỏ qua các thay đổi chưa lưu để chuyển sang bài mới?")) return;
  }
  if (id != null) {
    cacheCurrentForm();
  }
  id = null;
  const cached = songForms["new"];
  fields.forEach(k => {
    if (q(k)) q(k).value = (cached && cached[k] !== undefined) ? cached[k] : "";
  });
  if (q("key")) q("key").value = (cached && cached.key) ? cached.key : "C";
  if (q("sourceUrl")) q("sourceUrl").value = (cached && cached.sourceUrl) ? cached.sourceUrl : "";
  if (q("heading")) q("heading").textContent = "Thêm bài hát mới";
  previewTransposeSteps = 0;
  pendingReviewToken = null;
  drawList();
  checkValidation();
}

function scheduleAutoSave() {
  if (!isServerOnline) return;
  if (isDraftConflict || isRestoringDraft) return; // Dừng hoàn toàn autosave khi đang có xung đột phiên nháp với tab khác hoặc đang phục hồi nháp!
  clearTimeout(autoSaveTimer);
  const draftBadge = q("draftStatusBadge");
  if (draftBadge) {
    draftBadge.className = "badge badge-info";
    draftBadge.textContent = "Đang lưu nháp... ⏳";
  }

  autoSaveTimer = setTimeout(async () => {
    if (isDraftConflict) return;
    cacheCurrentForm();
    const currentSong = (id != null || q("title")?.value.trim()) ? {
      id: id || Date.now(),
      title: q("title")?.value.trim() || "",
      artist: q("artist")?.value.trim() || "",
      key: q("key")?.value.trim() || "C",
      audio: q("audio")?.value.trim() || "",
      sheet: q("sheet")?.value.trim() || "",
      content: q("content")?.value || "",
      sourceUrl: q("sourceUrl")?.value.trim() || ""
    } : null;

    try {
      const res = await fetch("/api/draft", {
        method: "PUT",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          activeSongId: id,
          song: currentSong,
          songForms,
          changes,
          baseRevision: globalThis.HOPAM_DATA_REVISION,
          baseLibraryHash,
          expectedDraftRevision: currentDraftRevision
        })
      });
      if (res.ok) {
        const data = await res.json();
        currentDraftRevision = data.draftRevision;
        if (draftBadge) {
          draftBadge.className = "badge badge-success";
          draftBadge.textContent = "Đã lưu nháp 💾";
        }
      } else if (res.status === 409) {
        isDraftConflict = true;
        clearTimeout(autoSaveTimer);
        if (draftBadge) {
          draftBadge.className = "badge badge-danger";
          draftBadge.textContent = "⚠️ Xung đột bản nháp (tab khác)";
        }
        showDraftConflictBanner("Bản nháp đã được lưu phiên bản mới hơn từ tab khác hoặc phiên làm việc khác. Chế độ tự động lưu tạm dừng để tránh ghi đè dữ liệu của phiên khác. Bạn có thể xuất bản nháp riêng hoặc tải lại nháp từ máy chủ.");
      } else {
        throw new Error("Lỗi khi lưu nháp.");
      }
    } catch {
      if (draftBadge) {
        draftBadge.className = "badge badge-danger";
        draftBadge.textContent = "Lưu nháp thất bại ❌";
      }
    }
  }, 600);
}

function save() {
  if (!q("title").value.trim() || !q("content").value.trim()) {
    checkValidation();
    return;
  }

  history.push(snapshotStudio(lib, changes, id));
  const editable = Object.fromEntries(fields.map(k => [k, q(k).value.trim()]));
  editable.key ||= "C";

  const result = saveSong(lib, id, editable, { sourceUrl: q("sourceUrl").value });
  lib = result.library;
  changes.push({ op: result.op, song: result.song });

  delete songForms[String(result.song.id)];
  delete songForms["new"];

  pendingReviewToken = null; // Invalidate review token when changes list is modified
  loadSong(result.song, false);
  updatePendingUi();
  q("status").textContent = "Đã lưu nháp vào danh sách chờ cập nhật.";
  scheduleAutoSave();
}

function remove() {
  if (!id) return;
  const isEmbeddedSmoke = window.parent !== window;
  if (!isEmbeddedSmoke && typeof window.confirm === "function") {
    if (!confirm(`Bạn có chắc chắn muốn xóa bài "${q("title").value}"?`)) return;
  }

  delete songForms[String(id)];
  history.push(snapshotStudio(lib, changes, id));
  changes.push({ op: "delete", songId: id });
  lib = lib.filter(s => s.id !== id);
  pendingReviewToken = null;
  blankSong(true);
  updatePendingUi();
  q("status").textContent = "Đã đánh dấu xóa bài.";
  scheduleAutoSave();
}

function undo() {
  if (history.length) {
    const state = history.pop();
    lib = state.library;
    changes = state.changes;
    if (state.selectedId != null) {
      delete songForms[String(state.selectedId)];
    }
    delete songForms["new"];
    pendingReviewToken = null;
    const selected = lib.find(s => String(s.id) === String(state.selectedId));
    selected ? loadSong(selected, false) : blankSong(true);
    updatePendingUi();
    q("status").textContent = "Đã hoàn tác.";
    scheduleAutoSave();
  }
}

// Cursor text insertion helper
function insertAtCursor(text) {
  const textarea = q("content");
  if (!textarea) return;
  textarea.focus();
  const start = textarea.selectionStart ?? textarea.value.length;
  const end = textarea.selectionEnd ?? textarea.value.length;
  const current = textarea.value;

  textarea.value = current.slice(0, start) + text + current.slice(end);
  const newPos = start + text.length;
  textarea.setSelectionRange(newPos, newPos);
  textarea.dispatchEvent(new Event("input", { bubbles: true }));
}

// Setup Event Listeners
function setupEvents() {
  // Search & input listeners
  q("search").oninput = drawList;
  fields.forEach(k => {
    if (q(k)) {
      q(k).oninput = () => {
        pendingReviewToken = null;
        checkValidation();
        scheduleAutoSave();
      };
    }
  });

  // Action buttons
  q("new").onclick = blankSong;
  q("save").onclick = save;
  q("remove").onclick = remove;
  q("undo").onclick = undo;

  // Insert toolbar chips
  document.querySelectorAll("#insertToolbar [data-insert]").forEach(btn => {
    btn.onclick = () => insertAtCursor(btn.dataset.insert);
  });

  if (q("btnCustomChord")) {
    q("btnCustomChord").onclick = () => {
      const chord = prompt("Nhập hợp âm (ví dụ: F#m7, Bbsus4):", "");
      if (chord && chord.trim()) {
        const clean = chord.trim().replace(/^\[+|\]+$/g, "");
        insertAtCursor(`[${clean}]`);
      }
    };
  }

  // Preview tools
  if (q("previewTransDown")) {
    q("previewTransDown").onclick = () => {
      previewTransposeSteps -= 1;
      updatePreview();
    };
  }
  if (q("previewTransUp")) {
    q("previewTransUp").onclick = () => {
      previewTransposeSteps += 1;
      updatePreview();
    };
  }
  if (q("previewTransReset")) {
    q("previewTransReset").onclick = () => {
      previewTransposeSteps = 0;
      updatePreview();
    };
  }
  if (q("previewToggleMobile")) {
    q("previewToggleMobile").onclick = () => {
      const stage = q("previewStage");
      stage.classList.toggle("mobile-view");
      const isMobile = stage.classList.contains("mobile-view");
      q("previewToggleMobile").textContent = isMobile ? "🖥 Toàn màn hình" : "📱 Khổ điện thoại (375px)";
    };
  }

  // MusicXML import
  q("xml").onchange = e => {
    const f = e.target.files[0];
    if (!f) return;
    const r = new FileReader();
    r.onload = () => {
      try {
        const s = parseMusicXml(r.result, f.name);
        blankSong();
        Object.entries(s).forEach(([k, v]) => {
          if (q(k)) q(k).value = v;
        });
        checkValidation();
        scheduleAutoSave();
      } catch (error) {
        q("status").textContent = error.message;
      }
    };
    r.readAsText(f);
  };

  // Pasted content import
  q("importPaste").onclick = () => {
    const pasted = q("hacPaste").value.trim();
    if (!pasted) return;
    q("content").value = pasted;
    checkValidation();
    scheduleAutoSave();
  };

  // Export fallbacks
  q("out").onclick = () =>
    download("songs.js", "const songs = " + JSON.stringify(lib, null, 2) + ";\n");

  q("exportChanges").onclick = () => {
    try {
      const set = makeChangeset(q("editorName").value, changes, globalThis.HOPAM_DATA_REVISION);
      download("changeset-" + Date.now() + ".json", JSON.stringify(set, null, 2));
      q("collabStatus").textContent = "Đã xuất changeset.";
    } catch (e) {
      q("collabStatus").textContent = e.message;
    }
  };

  // Update Library Modal
  if (q("updateLibraryBtn")) {
    q("updateLibraryBtn").onclick = openUpdateModal;
  }
  if (q("closeUpdateModalBtn")) {
    q("closeUpdateModalBtn").onclick = closeUpdateModal;
  }
  if (q("cancelUpdateBtn")) {
    q("cancelUpdateBtn").onclick = closeUpdateModal;
  }
  if (q("confirmUpdateBtn")) {
    q("confirmUpdateBtn").onclick = performLibraryUpdate;
  }

  // Backups Modal
  if (q("btnBackups")) {
    q("btnBackups").onclick = openBackupsModal;
  }
  if (q("closeBackupsModalBtn")) {
    q("closeBackupsModalBtn").onclick = closeBackupsModal;
  }
  if (q("closeBackupsBtn")) {
    q("closeBackupsBtn").onclick = closeBackupsModal;
  }

  // Publish Modal
  if (q("btnCheckPublish")) {
    q("btnCheckPublish").onclick = openPublishModal;
  }
  if (q("closePublishModalBtn")) {
    q("closePublishModalBtn").onclick = closePublishModal;
  }
  if (q("closePublishBtn")) {
    q("closePublishBtn").onclick = closePublishModal;
  }

  // Draft Conflict Banner
  if (q("btnExportConflictDraft")) {
    q("btnExportConflictDraft").onclick = exportLocalDraft;
  }
  if (q("btnReloadConflictDraft")) {
    q("btnReloadConflictDraft").onclick = () => reloadDraftFromServer(false);
  }
  if (q("btnDismissConflictBanner")) {
    q("btnDismissConflictBanner").onclick = hideDraftConflictBanner;
  }
}

function showDraftConflictBanner(msg) {
  const banner = q("draftConflictBanner");
  const msgEl = q("draftConflictMessage");
  if (banner && msgEl) {
    msgEl.textContent = msg || "Bản nháp trên đĩa thuộc về một phiên làm việc khác. Tự động lưu đã tạm dừng để tránh ghi đè nháp của tab khác. Bạn có thể xuất bản nháp riêng để lưu trữ an toàn hoặc tải lại nháp từ máy chủ.";
    banner.style.display = "block";
  }
}

function hideDraftConflictBanner() {
  const banner = q("draftConflictBanner");
  if (banner) banner.style.display = "none";
}

function exportLocalDraft() {
  cacheCurrentForm();
  const currentSong = (id != null || q("title")?.value.trim()) ? {
    id: id || Date.now(),
    title: q("title")?.value.trim() || "",
    artist: q("artist")?.value.trim() || "",
    key: q("key")?.value.trim() || "C",
    audio: q("audio")?.value.trim() || "",
    sheet: q("sheet")?.value.trim() || "",
    content: q("content")?.value || "",
    sourceUrl: q("sourceUrl")?.value.trim() || ""
  } : null;

  const exportData = {
    exportedAt: new Date().toISOString(),
    currentDraftRevision,
    activeSongId: id,
    song: currentSong,
    songForms,
    changes
  };

  download(`draft-conflict-backup-${Date.now()}.json`, JSON.stringify(exportData, null, 2));
}

async function reloadDraftFromServer(force = false) {
  // Chỉ cho phép bỏ xác nhận khi force === true được gọi rõ ràng
  if (force !== true && typeof window.confirm === "function") {
    const confirmed = confirm("Tải lại bản nháp từ máy chủ sẽ ghi đè các nội dung chưa lưu cục bộ trên màn hình này. Bạn có chắc chắn muốn tiếp tục?");
    if (!confirmed) {
      return; // Chọn Hủy: giữ nguyên toàn bộ nội dung và không tải nháp
    }
  }

  try {
    // 1. Tải cả /api/draft và /api/songs từ máy chủ trước khi thay đổi bất kỳ trạng thái giao diện nào
    const [draftRes, songsRes] = await Promise.all([
      fetch("/api/draft"),
      fetch("/api/songs")
    ]);
    if (!draftRes.ok) throw new Error("Không thể tải bản nháp từ máy chủ.");
    if (!songsRes.ok) throw new Error("Không thể tải danh sách bài hát từ máy chủ.");

    const [draftData, songsData] = await Promise.all([
      draftRes.json(),
      songsRes.json()
    ]);
    const draft = draftData.draft;
    const latestSongs = songsData.songs || [];
    const latestLibraryHash = songsData.libraryHash;

    // 2. Chỉ thay đổi trạng thái khi đã tải và kiểm tra đủ dữ liệu
    clearTimeout(autoSaveTimer);
    isRestoringDraft = true;

    // Trích xuất draftRevision chuẩn xác:
    if (draft && typeof draft.draftRevision === "number") {
      currentDraftRevision = draft.draftRevision;
    } else {
      currentDraftRevision = 0;
    }

    // Dựng thư viện làm việc từ latestSongs mới nhất từ máy chủ thay vì biến songs tĩnh lúc mở trang
    const baseLib = structuredClone(latestSongs);
    lib = baseLib;
    changes = [];
    songForms = {};
    history = [];
    pendingReviewToken = null;

    if (draft && draft.hasContent) {
      currentDraftData = draft;

      // Đồng bộ changes và dựng lại thư viện làm việc
      if (draft.changes && draft.changes.length > 0) {
        try {
          const applied = applyChangeset(baseLib, { changes: draft.changes }, globalThis.HOPAM_DATA_REVISION);
          lib = applied.songs;
          changes = draft.changes;
        } catch (err) {
          console.warn("Không thể dựng lại đầy đủ changeset:", err);
          changes = draft.changes;
        }
      }

      // Đồng bộ songForms
      if (draft.songForms) {
        songForms = structuredClone(draft.songForms);
      }

      // Đảm bảo draft.song được đưa vào songForms nếu thiếu
      const activeKey = (draft.activeSongId != null && draft.activeSongId !== "new")
        ? String(draft.activeSongId)
        : "new";
      if (draft.song && (!songForms[activeKey] || Object.keys(songForms[activeKey]).length === 0)) {
        songForms[activeKey] = structuredClone(draft.song);
      }

      // Đối chiếu hash hiện tại với baseLibraryHash của nháp; không tự nâng mốc nháp cũ để vượt kiểm tra xung đột
      if (draft.baseLibraryHash) {
        if (latestLibraryHash && draft.baseLibraryHash !== latestLibraryHash) {
          if (typeof window.alert === "function") {
            alert(`⚠️ CẢNH BÁO MỐC THƯ VIỆN:\nBản nháp được tạo trên phiên bản thư viện cũ (${draft.baseLibraryHash.slice(0, 8)} != ${latestLibraryHash.slice(0, 8)}). Vui lòng kiểm tra kỹ xung đột trước khi cập nhật!`);
          }
        }
        // Giữ đúng mốc của bản nháp, không tự ý gán thành latestLibraryHash
        baseLibraryHash = draft.baseLibraryHash;
      } else {
        baseLibraryHash = latestLibraryHash;
      }

      // Khôi phục active song vào form (isRestoringDraft = true nên cacheCurrentForm không làm bẩn songForms)
      if (draft.activeSongId != null && draft.activeSongId !== "new") {
        id = draft.activeSongId;
        const key = String(id);
        const baseSong = lib.find(s => String(s.id) === key) || {};
        const draftMatchingSong = (draft.song && String(draft.song.id) === key) ? draft.song : null;
        const cachedForm = songForms[key];
        const target = {
          ...baseSong,
          ...(draftMatchingSong || {}),
          ...(cachedForm || {})
        };
        loadSong(target, true);
      } else {
        id = null;
        if (draft.song) {
          songForms["new"] = { ...(songForms["new"] || {}), ...draft.song };
        }
        blankSong(true);
      }

      if (q("draftStatusBadge")) {
        q("draftStatusBadge").className = "badge badge-neutral";
        q("draftStatusBadge").textContent = "Đã đồng bộ nháp từ máy chủ";
      }
    } else {
      // Trường hợp tombstone (draft && !draft.hasContent) hoặc chưa có nháp (!draft)
      currentDraftData = null;
      id = null;
      baseLibraryHash = latestLibraryHash;
      blankSong(true);

      if (q("draftStatusBadge")) {
        q("draftStatusBadge").className = "badge badge-neutral";
        q("draftStatusBadge").textContent = draft ? "Bản nháp trống (tombstone)" : "Chưa có bản nháp";
      }
    }

    if (q("libStatusBadge")) {
      q("libStatusBadge").className = "badge badge-success";
      q("libStatusBadge").textContent = `Local Server Online · ${lib.length} bài`;
    }

    drawList();
    updatePendingUi();
    checkValidation();

    // Bật lại autosave và xóa cờ xung đột sau khi trạng thái nháp đã được khôi phục trọn vẹn
    isDraftConflict = false;
    isRestoringDraft = false;
    hideDraftConflictBanner();
  } catch (err) {
    isRestoringDraft = false;
    alert("Lỗi khi tải lại bản nháp: " + err.message);
  }
}

